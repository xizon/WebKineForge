import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { SiteInfo } from '../utils/types.ts';
import { consoleColors } from '../utils/helper.ts';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '../..');
const sitesRoot = path.join(projectRoot, 'sites');

const { GREEN, RESET } = consoleColors;

function readSites(): SiteInfo[] {
    if (!fs.existsSync(sitesRoot)) {
        throw new Error(`Sites directory not found: ${sitesRoot}`);
    }

    return fs.readdirSync(sitesRoot, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .flatMap(entry => {
            const root = path.join(sitesRoot, entry.name);
            const configPath = path.join(root, 'site.json');

            if (!fs.existsSync(configPath)) return [];

            const config = JSON.parse(
                fs.readFileSync(configPath, 'utf-8')
            );

            if (config.name !== entry.name) {
                console.warn(
                    `[WKF] Skipping ${entry.name}: site.json name does not match directory name.`
                );
                return [];
            }

            const site: SiteInfo = {
                name: config.name,
                root,
                components: []
            };

            return [site];
        });
}

function generatePaths(currentSite: SiteInfo, allSites: SiteInfo[]) {
    const paths: Record<string, string[]> = {
        '@/*': ['./src/*'],
        '@/components/*': ['./src/components/*'],
        '@/pages/*': ['./src/pages/*'],
        '@/styles/*': ['./src/styles/*'],
        '@/core/*': ['../../core/*'],
    };

    // Register wildcard aliases for other Sites.
    for (const site of allSites) {
        if (site.name === currentSite.name) continue;

        const componentsPath = path.relative(
            currentSite.root,
            path.join(site.root, 'src/components')
        ).split(path.sep).join('/');

        const assetsPath = path.relative(
            currentSite.root,
            path.join(site.root, 'public/assets')
        ).split(path.sep).join('/');

        paths[`@/site/${site.name}/components/*`] = [
            `./${componentsPath}/*`
        ];

        paths[`@/site/${site.name}/assets/*`] = [
            `./${assetsPath}/*`
        ];
    }

    return paths;
}

function generateSiteTsconfig(
    site: SiteInfo,
    allSites: SiteInfo[]
) {
    const configPath = path.join(site.root, 'tsconfig.json');

    const config = {
        _meta: {
            generated: true,
            notice: 'Automatically generated by system. Do not edit manually.'
        },
        extends: '../../tsconfig.json',
        compilerOptions: {
            paths: generatePaths(site, allSites)
        },
        include: [
            'src',
            '.wkf/playground/entries/**/*.tsx'
        ]
    };

    fs.writeFileSync(
        configPath,
        `${JSON.stringify(config, null, 2)}\n`,
        'utf-8'
    );

    console.log(
        `${GREEN}[WKF] Generated: sites/${site.name}/tsconfig.json${RESET}`
    );
}

function main() {
    const sites = readSites();

    if (sites.length === 0) {
        console.warn('[WKF] No valid sites found.');
        return;
    }

    for (const site of sites) {
        generateSiteTsconfig(site, sites);
    }

    console.log(
        `${GREEN}[WKF] Generated TypeScript configurations for ${sites.length} sites.${RESET}`
    );
}

main();